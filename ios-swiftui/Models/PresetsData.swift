import SwiftUI

public struct CategoryModel: Identifiable, Equatable {
    public let id: Int
    public let name: String
    public let icon: String
    public let colorHex: String
    
    public init(id: Int, name: String, icon: String, colorHex: String) {
        self.id = id
        self.name = name
        self.icon = icon
        self.colorHex = colorHex
    }
}

public struct PresetModel: Identifiable, Equatable {
    public let id: Int
    public let name: String
    public let icon: String
    public let colorHex: String
    public let timeOfDay: TimeOfDay
    public let trackingType: HabitTrackingType
    public let targetAmount: Double
    public let unit: String
    public let stepAmount: Double
    public let targetReps: Int
    public let targetDurationMinutes: Int
    public let categoryIds: [Int]
    
    public init(
        id: Int,
        name: String,
        icon: String,
        colorHex: String,
        timeOfDay: TimeOfDay,
        trackingType: HabitTrackingType,
        targetAmount: Double,
        unit: String,
        stepAmount: Double,
        targetReps: Int,
        targetDurationMinutes: Int,
        categoryIds: [Int]
    ) {
        self.id = id
        self.name = name
        self.icon = icon
        self.colorHex = colorHex
        self.timeOfDay = timeOfDay
        self.trackingType = trackingType
        self.targetAmount = targetAmount
        self.unit = unit
        self.stepAmount = stepAmount
        self.targetReps = targetReps
        self.targetDurationMinutes = targetDurationMinutes
        self.categoryIds = categoryIds
    }
}

